#!/usr/bin/env bash
# lab-ssh.sh — ssh into a lab guest over AF_VSOCK (no guest IP, no host port).
#   export LAB_PREFIX=myproject
#   ./lab-ssh.sh                          # interactive shell on <prefix>-target
#   ./lab-ssh.sh myproject-target uname -r
#   ./lab-ssh.sh myproject-target --wait  # block until sshd answers (used by lab-up.sh)
#   ./lab-ssh.sh --config                 # print the generated ssh config's path
#
# Writes a lab-only ssh config that gives every <prefix>-* guest a plain alias
# (its domain name) routed through libvirt's ssh proxy (package libvirt-ssh-proxy)
# over vsock; the guest's systemd starts sshd on vsock by itself. Use the same
# file for copies, which cannot take the proxy's own qemu:system/<vm> names
# (scp and rsync split them at the colon):
#   scp   -F "$(./lab-ssh.sh --config)" file myproject-target:
#   rsync -e "ssh -F $(./lab-ssh.sh --config)" -a dir/ myproject-target:dir/
# Guest host keys go to a lab-only known_hosts file, never ~/.ssh/known_hosts.
set -euo pipefail
LAB_PREFIX="${LAB_PREFIX:-lab}"
CACHE_DIR="${LAB_CACHE:-$HOME/.cache/${LAB_PREFIX}-lab}"
SSH_PUBKEY="${SSH_PUBKEY:-$HOME/.ssh/id_ed25519.pub}"
CFG="$CACHE_DIR/ssh_config"
mkdir -p "$CACHE_DIR"
cat >"$CFG" <<EOF_CFG
# generated by lab-ssh.sh; ssh -F $CFG ${LAB_PREFIX}-target
Host ${LAB_PREFIX}-*
    HostName qemu:system/%h
    User ${GUEST_USER:-fedora}
    ProxyCommand /usr/libexec/libvirt-ssh-proxy %h %p
    ProxyUseFdpass yes
    CheckHostIP no
    StrictHostKeyChecking accept-new
    UserKnownHostsFile $CACHE_DIR/known_hosts
    IdentityFile ${SSH_PUBKEY%.pub}
EOF_CFG
if [[ "${1:-}" = "--config" ]]; then echo "$CFG"; exit 0; fi
VM="${1:-${TARGET_VM:-${LAB_PREFIX}-target}}"
[[ $# -gt 0 ]] && shift
if [[ "${1:-}" = "--wait" ]]; then
  for _ in $(seq 1 "${WAIT_TRIES:-60}"); do
    ssh -F "$CFG" -o ConnectTimeout=5 -o BatchMode=yes "$VM" true 2>/dev/null && exit 0
    sleep 3
  done
  echo "$VM: no ssh over vsock yet (running? first boot finished?)" >&2
  exit 1
fi
exec ssh -F "$CFG" "$VM" "$@"
